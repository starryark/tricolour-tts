"""Untrained reference checkpoints for T1: the init weights with our 14 locked rows written
by the trainer's own save_checkpoint, so "B0" (Base + vectors) and "C0" (CustomVoice +
rows) are generated by the same gen_eval.py path as the trained checkpoints.

    python make_step0.py --init <model dir> --row0 3000 --table speaker_table.pt --out runs/B0/checkpoint-step-0
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import train_sft as T  # noqa: E402


def main() -> None:
    import torch
    from qwen_tts import Qwen3TTSModel

    ap = argparse.ArgumentParser()
    ap.add_argument("--init", required=True)
    ap.add_argument("--row0", type=int, required=True)
    ap.add_argument("--table", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    base_dir = T.resolve_base_dir(a.init)
    w = Qwen3TTSModel.from_pretrained(str(base_dir), dtype=torch.bfloat16)
    tab = torch.load(a.table)
    sd = {k: v.detach().to("cpu") for k, v in w.model.state_dict().items()}
    T.save_checkpoint(Path(a.out), base_dir, sd, tab["table"].to(torch.bfloat16), [n.lower() for n in tab["names"]],
                      None, None, a.row0)


if __name__ == "__main__":
    main()
